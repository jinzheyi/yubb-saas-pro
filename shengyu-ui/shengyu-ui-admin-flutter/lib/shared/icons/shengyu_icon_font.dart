class ShengyuFileIconSpec {
  const ShengyuFileIconSpec({
    required this.icon,
    required this.color,
    required this.backgroundColor,
  });

  final IconData icon;
  final Color color;
  final Color backgroundColor;
}

ShengyuFileIconSpec resolveShengyuFileIcon(
  String mimeType, {
  String? fileName,
}) {
  final normalizedMimeType = mimeType.toLowerCase();
  final normalizedFileName = fileName?.trim().toLowerCase() ?? '';
  final source = '$normalizedMimeType $normalizedFileName';

  if (normalizedMimeType.startsWith('image/')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileImage,
      color: Color(0xFF8F4CFF),
      backgroundColor: Color(0xFFF3EDFF),
    );
  }
  if (normalizedMimeType.startsWith('video/')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileVideo,
      color: Color(0xFFE85D75),
      backgroundColor: Color(0xFFFFEDF1),
    );
  }
  if (normalizedMimeType.startsWith('audio/')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileAudio,
      color: Color(0xFF00A870),
      backgroundColor: Color(0xFFEAFBF5),
    );
  }
  if (source.contains('pdf')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.filePdf,
      color: Color(0xFFE34D59),
      backgroundColor: Color(0xFFFFEEF0),
    );
  }
  if (source.contains('word') ||
      source.contains('document') ||
      source.contains('docx') ||
      source.contains('doc') ||
      source.contains('officedocument.wordprocessingml')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileWord,
      color: Color(0xFF246BFD),
      backgroundColor: Color(0xFFEEF3FF),
    );
  }
  if (source.contains('sheet') ||
      source.contains('excel') ||
      source.contains('spreadsheet') ||
      source.contains('xlsx') ||
      source.contains('xls') ||
      source.contains('csv')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileSpreadsheet,
      color: Color(0xFF2BA471),
      backgroundColor: Color(0xFFEAFBF5),
    );
  }
  if (source.contains('presentation') ||
      source.contains('powerpoint') ||
      source.contains('pptx') ||
      source.contains('ppt')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.filePresentation,
      color: Color(0xFFFF8A00),
      backgroundColor: Color(0xFFFFF4E8),
    );
  }
  if (source.contains('zip') ||
      source.contains('rar') ||
      source.contains('7z') ||
      source.contains('tar') ||
      source.contains('gz')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileZip,
      color: Color(0xFF6E7B8F),
      backgroundColor: Color(0xFFF2F4F8),
    );
  }
  if (source.contains('folder') || source.contains('directory')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileFolder,
      color: Color(0xFFFFB020),
      backgroundColor: Color(0xFFFFF6E5),
    );
  }
  if (source.contains('html') || source.contains('htm')) {
    return const ShengyuFileIconSpec(
      icon: ShengyuIconFont.fileHtml,
      color: Color(0xFFFF6A3D),
      backgroundColor: Color(0xFFFFF0EA),
    );
  }
  return const ShengyuFileIconSpec(
    icon: ShengyuIconFont.fileGeneric,
    color: Color(0xFF246BFD),
    backgroundColor: Color(0xFFEEF3FF),
  );
}
